/** Pick one micro-action for a sphere, rotating daily so it feels fresh. */
export function pickMicroAction(sphereId: string): string {
  const actions = MICRO_ACTIONS[sphereId] ?? MICRO_ACTIONS.growth;
  const day = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  return actions[day % actions.length];
}

